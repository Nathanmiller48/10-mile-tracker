/** Parse the source file into a Map of "Book C:V" -> text. */
export function parseSource(text) {
  const verses = new Map();
  for (const line of text.replace(/^﻿/, '').split(/\r?\n/)) {
    const tab = line.indexOf('\t');
    if (tab < 0) continue;
    const ref = line.slice(0, tab).trim();
    if (/^.+ \d+:\d+$/.test(ref)) verses.set(ref, line.slice(tab + 1).trim());
  }
  return verses;
}

/** "Psalm 23:1-2" -> ['Psalm 23:1', 'Psalm 23:2'] */
export function expand(reference) {
  const m = reference.match(/^(.+ \d+):(\d+)(?:-(\d+))?$/);
  if (!m) throw new Error(`build-verses: bad reference "${reference}"`);
  const from = Number(m[2]);
  const to = m[3] ? Number(m[3]) : from;
  return Array.from({ length: to - from + 1 }, (_, i) => `${m[1]}:${from + i}`);
}

/** The text of a reference, exactly as the source has it (verses joined by one space). */
export function textFor(reference, source) {
  return expand(reference)
    .map((ref) => {
      const text = source.get(ref);
      if (!text) throw new Error(`build-verses: "${ref}" is not in the source file`);
      return text;
    })
    .join(' ');
}

export function renderVersesModule(source) {
  const verses = REFERENCES.map((ref) => ({ ref, text: textFor(ref, source) }));
  return `// GENERATED by scripts/build-verses.mjs from tests/fixtures/bsb.txt. Do not edit by hand.
// Berean Standard Bible, dedicated to the public domain (BereanBible.com).

export const VERSES = ${JSON.stringify(verses, null, 1)};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = parseSource(await readFile(BSB_TXT, 'utf8'));
  await writeFile(VERSES_JS, renderVersesModule(source));
  console.log(`Wrote ${REFERENCES.length} verses to js/data/verses.js`);
}
