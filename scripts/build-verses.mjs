  '2 Timothy 4:7', '2 Timothy 1:7', '2 Timothy 2:5', '1 Timothy 4:8',
  'Galatians 6:9', 'Romans 5:3-4', 'Romans 8:18', 'Romans 12:11', 'Romans 12:12', 'Romans 15:13',
